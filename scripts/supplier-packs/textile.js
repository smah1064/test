/* Supplier pack: roll-to-roll textile printing (fabric by the metre, upholstery, bed sheets, duvet covers, curtains).
 * The customer designs one square tile; it repeats over the whole fabric (src/products.js "Roll-to-roll fabric",
 * public/js/editor.js exportTile, src/app.js pattern, src/printfiles.js repeatPreview). */
const L = (s) => `<span dir="ltr">${s}</span>`;
const WH = (w, h) => `عرض ${L(w)} × ارتفاع ${L(h)} سم`;
// Tile sizes, fabric sizes and repeats are read from the product data, so the pack can't drift from the site.
const { PRODUCTS } = require('../../src/products');
const P = (id) => PRODUCTS.find((p) => p.id === id);
// The editor's export (public/js/editor.js exportPrint): 300 DPI, less when the tile would pass 16 million pixels or 8000 px a side.
const tileDpi = (tileCm) => Math.floor(Math.min(300, Math.sqrt(16e6) / (tileCm / 2.54), 8000 / (tileCm / 2.54)));
const TILES = [...new Set(PRODUCTS.filter((p) => p.process === 'textile').flatMap((p) => p.pattern.tiles))].sort((a, b) => a - b);
const tilesOf = (id) => P(id).pattern.tiles.map((t) => `${L(`${t} × ${t}`)} سم (${L(`${tileDpi(t)} DPI`)})`).join('، ');
const tileRows = (id) => [
  ['مقاسات الوحدة المتاحة للعميل', tilesOf(id)],
  ['المقاس اللي في الرسم', `${L(P(id).pattern.tile)} سم (المقاس اللي بيبدأ بيه العميل)`],
];
const firstWord = (z) => z.label.ar.split(' · ')[0];
/** Made-up pieces: each size as width and height of the printed fabric. */
const pieceSizes = (id) => P(id).sizes.map((z) => `${firstWord(z)}: ${WH(z.cm[0], z.cm[1])}`).join(' · ');
const curtainSizes = () => P('curtains').sizes.map((z) => `${WH(z.cm[0] / 2, z.cm[1])}`).join(' · ');
const rollWidth = (id) => P(id).sizes[0].cm[0];
const maxLen = (id) => Math.max(...P(id).sizes.map((z) => z.cm[1])) / 100;
const widest = Math.max(...['bedsheet', 'duvetcover'].flatMap((id) => P(id).sizes.map((z) => z.cm[0])));

